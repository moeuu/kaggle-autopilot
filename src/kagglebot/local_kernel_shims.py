        "    if path.suffix.lower() == '.dbf':",
        "        return path",
        "    exact = path.with_suffix('.dbf')",
        "    if exact.exists():",
        "        return exact",
        "    lowered_stem = path.stem.lower()",
        "    for candidate in path.parent.iterdir():",
        "        if (",
        "            candidate.is_file()",
        "            and candidate.suffix.lower() == '.dbf'",
