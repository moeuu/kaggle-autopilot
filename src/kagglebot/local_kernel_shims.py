        "def _kb_parse_dbf_value(raw_value, field_type, decimal_count, encoding):",
        "    text = raw_value.decode(encoding, errors='replace').strip()",
        "    if not text:",
        "        return None",
        "    normalized_type = field_type.upper()",
        "    if normalized_type in {'N', 'F', 'B'}:",
        "        try:",
        "            if decimal_count or any(marker in text for marker in ('.', 'e', 'E')):",
        "                return float(text)",
        "            return int(text)",
        "        except ValueError:",
        "            return text",
        "    if normalized_type == 'L':",
        "        marker = text[:1].upper()",
        "        if marker in {'Y', 'T'}:",
        "            return True",
        "        if marker in {'N', 'F'}:",
        "            return False",
        "        return None",
        "    if normalized_type == 'D' and len(text) == 8 and text.isdigit():",
        "        return f'{text[:4]}-{text[4:6]}-{text[6:]}'",
        "    return text",
        "",
