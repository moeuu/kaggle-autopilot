        "    cpg_path = path.with_suffix('.cpg')",
        "    if cpg_path.exists():",
        "        raw_encoding = cpg_path.read_text(encoding='ascii', errors='ignore').strip()",
        "        if raw_encoding:",
        "            return 'utf-8' if raw_encoding == '65001' else raw_encoding",
        "    return 'latin1'",
